"""Signed Steam Certificate (SSC) protocol codec and validator for Marathon.

Implements BAP Service 304 (CMsgSteamDatagramCertificateRequest) parsing and
BAP Service 305 (CMsgSteamDatagramCertificateSigned) serialization and validation.

All synthetic responses generated by this module are non-production test fixtures
and are NOT valid for production Steam authentication.
"""
from dataclasses import dataclass
import hashlib
import struct
import time
from typing import Optional, List, Dict, Any, Tuple

from marathon_protobuf import ProtobufWriter, decode_varint
from ssc_public_capture import fields, one

# Service Identifiers
SERVICE_SSC_REQUEST = 304
SERVICE_SSC_RESPONSE = 305

# Key Types
KEY_TYPE_INVALID = 0
KEY_TYPE_ED25519 = 1

# Standard Default Values for Marathon Build 248199
DEFAULT_MARATHON_APP_ID = 3065800
DEFAULT_STEAM_ID = 76561198000001001

@dataclass
class SscRequestMetadata:
    """Structured representation of a decoded BAP Service 304 certificate request."""
    task_id: int
    key_type: int
    public_key: bytes
    legacy_steam_id: Optional[int] = None
    identity_string: Optional[str] = None
    app_ids: Optional[List[int]] = None
    payload_sha256: str = ""
    raw_payload_len: int = 0
    body_offset: int = 0

@dataclass
class SscResponseMetadata:
    """Structured representation of a decoded BAP Service 305 certificate response."""
    cert_bytes: bytes
    ca_key_id: int
    ca_signature: bytes
    key_type: int
    public_key: bytes
    legacy_steam_id: Optional[int]
    time_created: int
    time_expiry: int
    app_ids: List[int]
    identity_string: Optional[str]


def parse_ssc_request(payload: bytes, task_id: int = 2) -> Optional[SscRequestMetadata]:
    """Parse and validate an incoming Service 304 request payload.
    
    Service 304 contains an outer envelope with Field 3 (wire type 2)
    wrapping CMsgSteamDatagramCertificateRequest.
    """
    raw_bytes = bytes(payload)
    sha = hashlib.sha256(raw_bytes).hexdigest()
    
    for offset in ([2, 0] if raw_bytes.startswith(bytes(2)) else [0, 2]):
        if offset > len(raw_bytes):
            continue
        try:
            outer = fields(raw_bytes[offset:])
            csr_bytes = one(outer, 3, 2)
            if not csr_bytes:
                continue
            csr = fields(csr_bytes)
            cert_bytes = one(csr, 1, 2)
            if not cert_bytes:
                continue
            cert = fields(cert_bytes)
            key_type = one(cert, 1, 0)
            key_data = one(cert, 2, 2, b"")
            if key_type != KEY_TYPE_ED25519 or len(key_data) != 32:
                continue
            
            steam_id = None
            raw_sid = one(cert, 4, 1)
            if raw_sid and len(raw_sid) == 8:
                steam_id = struct.unpack("<Q", raw_sid)[0]
                
            ident_str = None
            raw_ident = one(cert, 12, 2)
            if raw_ident:
                ident_str = raw_ident.decode("utf-8", errors="replace")
                
            app_ids = [val for (n, w), vals in cert.items() if (n, w) == (10, 0) for val in vals]
            
            return SscRequestMetadata(
                task_id=task_id,
                key_type=key_type,
                public_key=key_data,
                legacy_steam_id=steam_id,
                identity_string=ident_str,
                app_ids=app_ids or None,
                payload_sha256=sha,
                raw_payload_len=len(raw_bytes),
                body_offset=offset
            )
        except (ValueError, struct.error, IndexError):
            continue
    return None


def build_inner_certificate(public_key: bytes, steam_id: int = DEFAULT_STEAM_ID,
                           app_id: int = DEFAULT_MARATHON_APP_ID,
                           valid_duration_seconds: int = 86400,
                           created_timestamp: Optional[int] = None) -> bytes:
    """Build serialized CMsgSteamDatagramCertificate conforming to Marathon's schema."""
    now = created_timestamp if created_timestamp is not None else int(time.time())
    w = ProtobufWriter()
    # Field 1: key_type (enum, varint) = 1 (ED25519)
    w.varint(1, KEY_TYPE_ED25519)
    # Field 2: key_data (bytes) = 32 bytes ephemeral public key
    w.bytes(2, public_key)
    # Field 4: legacy_steam_id (fixed64)
    w.fixed64(4, steam_id)
    # Field 8: time_created (fixed32)
    w.fixed32(8, now)
    # Field 9: time_expiry (fixed32)
    w.fixed32(9, now + valid_duration_seconds)
    # Field 10: app_ids (repeated uint32, varint)
    w.varint(10, app_id)
    # Field 12: identity_string (string)
    w.string(12, f"steamid:{steam_id}")
    return w.build()


def build_signed_certificate_container(cert_bytes: bytes, ca_key_id: int = 0x01,
                                      ca_signature: bytes = b"\x00" * 64) -> bytes:
    """Build serialized CMsgSteamDatagramCertificateSigned container."""
    w = ProtobufWriter()
    # Field 4: cert (bytes)
    w.bytes(4, cert_bytes)
    # Field 5: ca_key_id (fixed64)
    w.fixed64(5, ca_key_id)
    # Field 6: ca_signature (bytes)
    w.bytes(6, ca_signature)
    return w.build()


def build_service_305_response_body(signed_container: bytes) -> bytes:
    """Build complete Service 305 response body wrapping the signed certificate."""
    w = ProtobufWriter()
    # Outer Service 305 body: Field 3 = CMsgSteamDatagramCertificateSigned
    w.bytes(3, signed_container)
    return w.build()


def build_synthetic_ssc_response(public_key: bytes, steam_id: int = DEFAULT_STEAM_ID,
                                app_id: int = DEFAULT_MARATHON_APP_ID,
                                ca_key_id: int = 0x01,
                                ca_signature: bytes = b"\x00" * 64,
                                valid_duration_seconds: int = 86400,
                                created_timestamp: Optional[int] = None) -> bytes:
    """Generate a structurally valid Service 305 response fixture for offline testing.
    
    WARNING: This produces a NON-PRODUCTION test fixture. It is NOT valid for production
    Steam authentication and cannot authenticate with remote Steam Relays.
    """
    inner = build_inner_certificate(public_key, steam_id, app_id, valid_duration_seconds, created_timestamp)
    container = build_signed_certificate_container(inner, ca_key_id, ca_signature)
    return build_service_305_response_body(container)


def parse_ssc_response(body: bytes) -> Optional[SscResponseMetadata]:
    """Parse and validate a Service 305 response body."""
    try:
        outer = fields(bytes(body))
        container_bytes = one(outer, 3, 2)
        if not container_bytes:
            return None
        container = fields(container_bytes)
        cert_bytes = one(container, 4, 2)
        raw_ca_key_id = one(container, 5, 1)
        ca_sig = one(container, 6, 2)
        if not cert_bytes or not raw_ca_key_id or not ca_sig:
            return None
        ca_key_id = struct.unpack("<Q", raw_ca_key_id)[0]
        
        cert = fields(cert_bytes)
        key_type = one(cert, 1, 0)
        key_data = one(cert, 2, 2, b"")
        raw_sid = one(cert, 4, 1)
        steam_id = struct.unpack("<Q", raw_sid)[0] if raw_sid else None
        
        raw_created = one(cert, 8, 5)
        raw_expiry = one(cert, 9, 5)
        if not raw_created or not raw_expiry:
            return None
        time_created = struct.unpack("<I", raw_created)[0]
        time_expiry = struct.unpack("<I", raw_expiry)[0]
        
        app_ids = [val for (n, w), vals in cert.items() if (n, w) == (10, 0) for val in vals]
        raw_ident = one(cert, 12, 2)
        ident_str = raw_ident.decode("utf-8", errors="replace") if raw_ident else None
        
        return SscResponseMetadata(
            cert_bytes=cert_bytes,
            ca_key_id=ca_key_id,
            ca_signature=ca_sig,
            key_type=key_type,
            public_key=key_data,
            legacy_steam_id=steam_id,
            time_created=time_created,
            time_expiry=time_expiry,
            app_ids=app_ids,
            identity_string=ident_str
        )
    except (ValueError, struct.error, IndexError):
        return None
